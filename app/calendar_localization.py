"""Server dates agree with the existing browser Intl Persian calendar.

Year starts are generated by scripts/build_calendar_data.cjs, not inferred from
a second Jalali algorithm. Canonical stored dates always remain Gregorian.
"""
from bisect import bisect_right
from datetime import date
import json
from pathlib import Path

_data=json.loads((Path(__file__).parents[1]/'static/persian-calendar.json').read_text(encoding='utf-8'))
_starts=tuple(date.fromisoformat(s).toordinal() for s in _data['year_starts'])


def persian_parts(value: date) -> tuple[int,int,int]:
    ordinal=value.toordinal()
    if not _starts[0]<=ordinal<_starts[-1]:
        raise ValueError('Date is outside the supported Persian calendar range.')
    index=bisect_right(_starts,ordinal)-1
    offset=ordinal-_starts[index]
    month,day=divmod(offset,31) if offset<186 else divmod(offset-186,30)
    return _data['first_year']+index,month+(1 if offset<186 else 7),day+1
